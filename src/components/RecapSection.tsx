import { useCallback, useMemo, useState } from "react";
import { Flag, FileText, Download, Copy, Check } from "lucide-react";
import { Link } from "react-router-dom";
import type { ModeratedMessage, StreamContext } from "../lib/types";
import { chatHealthSeries, groupQuestions } from "../lib/policy";
import { effectiveAction } from "./ChatColumn";
import { requestRecap, type Recap } from "../lib/jev";
import { supabase } from "../lib/supabase";

function makeSlug(): string {
  const words = [
    "chat", "stream", "queue", "health", "recap", "spoiler", "highlight",
  ];
  const w = words[Math.floor(Math.random() * words.length)];
  return `${w}-${Math.random().toString(36).slice(2, 8)}`;
}

export function RecapSection({
  messages,
  streamContext,
  writerMode,
  saveState,
  setSaveState,
}: {
  messages: ModeratedMessage[];
  streamContext: StreamContext;
  writerMode: "llm" | "mock";
  saveState: "idle" | "saving" | "saved" | "error";
  setSaveState: (s: "idle" | "saving" | "saved" | "error") => void;
}) {
  const [recap, setRecap] = useState<Recap | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [slug, setSlug] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  const aggregates = useMemo(() => {
    const health = chatHealthSeries(messages);
    const avgHealth =
      health.length > 0
        ? health.reduce((s, p) => s + p.health, 0) / health.length
        : 0;
    const questions = groupQuestions(messages);
    return {
      stats: {
        messages_checked: messages.length,
        hidden: messages.filter((m) => effectiveAction(m) === "hidden").length,
        spoilers_blurred: messages.filter((m) => m.action === "spoiler").length,
        flagged: messages.filter((m) => m.action === "review").length,
        overrides: messages.filter((m) => m.override !== null).length,
        avg_health: Math.round(avgHealth),
        avg_latency_ms: (() => {
          const withLatency = messages.filter(
            (m) => !m.fallback && m.latency_ms != null && m.latency_ms > 0,
          );
          return withLatency.length > 0
            ? Math.round(
                withLatency.reduce((s, m) => s + (m.latency_ms ?? 0), 0) /
                  withLatency.length,
              )
            : 0;
        })(),
      },
      highlights: messages
        .filter((m) => effectiveAction(m) === "highlight")
        .slice(0, 10)
        .map((m) => `${m.username}: ${m.text}`),
      top_questions: questions.slice(0, 5).map((q) => q.question),
    };
  }, [messages]);

  const generate = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const r = await requestRecap(aggregates, streamContext, writerMode);
      setRecap(r);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Couldn't write the recap.");
    } finally {
      setLoading(false);
    }
  }, [aggregates, streamContext, writerMode]);

  const saveReport = useCallback(async () => {
    if (!recap) return;
    setSaveState("saving");
    const newSlug = makeSlug();
    const { error: err } = await supabase.from("sessions").insert({
      slug: newSlug,
      source:
        streamContext.title || "simulation",
      stream_context: streamContext,
      policy: {},
      stats: aggregates.stats,
      recap,
      writer_mode: writerMode,
    });
    if (err) {
      setSaveState("error");
      return;
    }
    setSlug(newSlug);
    setSaveState("saved");
  }, [recap, aggregates, streamContext, writerMode, setSaveState]);

  const markdown = useMemo(() => {
    if (!recap) return "";
    return [
      `# ModSquad stream recap`,
      ``,
      `**${recap.headline}**`,
      ``,
      `## Highlights`,
      ...recap.highlights.map((h) => `- ${h}`),
      ``,
      `## Top questions`,
      ...recap.top_questions.map((q) => `- ${q}`),
      ``,
      `## Moderation summary`,
      recap.mod_summary,
      ``,
      `## Chat mood`,
      recap.chat_mood,
      ``,
      `---`,
      `Generated by ModSquad (simulation only — never posts to real chats).`,
    ].join("\n");
  }, [recap]);

  const download = useCallback(() => {
    const blob = new Blob([markdown], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "modsquad-recap.md";
    a.click();
    URL.revokeObjectURL(url);
  }, [markdown]);

  return (
    <div className="panel flex flex-col">
      <div className="flex items-center justify-between border-b border-studio-700/70 px-4 py-2.5">
        <h2 className="flex items-center gap-1.5 text-sm font-semibold">
          <Flag className="h-4 w-4 text-spoiler-400" />
          End-of-stream recap
        </h2>
      </div>
      <div className="space-y-3 p-3">
        {!recap && (
          <button
            className="btn-primary w-full py-2"
            onClick={generate}
            disabled={loading || messages.length === 0}
          >
            {loading ? "Writing…" : "End stream & write recap"}
          </button>
        )}
        {error && (
          <p className="rounded-lg bg-toxic-500/10 p-2 text-xs text-toxic-400">
            {error} — try the Mock writer toggle.
          </p>
        )}
        {recap && (
          <>
            <div className="space-y-2.5 text-sm">
              <p className="font-semibold text-studio-100">{recap.headline}</p>
              <div>
                <p className="mb-1 text-[10px] font-semibold uppercase tracking-wide text-studio-400">
                  Highlights
                </p>
                <ul className="list-inside list-disc space-y-0.5 text-xs text-studio-200">
                  {recap.highlights.map((h, i) => (
                    <li key={i}>{h}</li>
                  ))}
                </ul>
              </div>
              {recap.top_questions.length > 0 && (
                <div>
                  <p className="mb-1 text-[10px] font-semibold uppercase tracking-wide text-studio-400">
                    Top questions
                  </p>
                  <ul className="list-inside list-disc space-y-0.5 text-xs text-studio-200">
                    {recap.top_questions.map((q, i) => (
                      <li key={i}>{q}</li>
                    ))}
                  </ul>
                </div>
              )}
              <p className="rounded-lg bg-studio-850 p-2 text-xs text-studio-300">
                {recap.mod_summary}
              </p>
              <p className="text-xs text-studio-400">
                Mood: <span className="font-semibold text-spoiler-400">{recap.chat_mood}</span>
              </p>
            </div>
            <div className="flex flex-wrap gap-2">
              <button
                className="btn-ghost flex-1 py-1 text-xs"
                onClick={saveReport}
                disabled={saveState === "saving"}
              >
                <FileText className="h-3.5 w-3.5" />
                {saveState === "saving"
                  ? "Saving…"
                  : saveState === "saved"
                    ? "Saved"
                    : "Create report"}
              </button>
              <button className="btn-ghost flex-1 py-1 text-xs" onClick={download}>
                <Download className="h-3.5 w-3.5" /> Export Markdown
              </button>
              <button
                className="btn-ghost py-1 text-xs"
                onClick={() => {
                  void navigator.clipboard.writeText(markdown).then(() => {
                    setCopied(true);
                    setTimeout(() => setCopied(false), 1500);
                  });
                }}
                title="Copy Markdown"
              >
                {copied ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
              </button>
            </div>
            {saveState === "saved" && slug && (
              <Link
                to={`/r/${slug}`}
                className="block rounded-lg border border-question-500/40 bg-question-500/10 p-2 text-center text-xs font-medium text-question-400 hover:bg-question-500/20"
              >
                Report ready — open /r/{slug}
              </Link>
            )}
            {saveState === "error" && (
              <p className="text-xs text-toxic-400">
                Couldn't save the report. Check the database connection.
              </p>
            )}
          </>
        )}
      </div>
    </div>
  );
}
